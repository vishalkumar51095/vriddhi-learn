#!/usr/bin/env python3
"""
Turns a question-bank JSON file into Flyway migrations for content-service (categories, subjects,
topics, questions, options, tags) and exam-service (mock papers).

    python3 infra/tools/gen_seed_sql.py infra/seed-data/ugc_net.json \
        --content-out backend/content-service/src/main/resources/db/migration/V3__seed_ugc_net.sql \
        --exam-out    backend/exam-service/src/main/resources/db/migration/V4__seed_ugc_net_papers.sql

IDs are uuid5 of the names, so the same JSON always yields the same ids — that is what lets the
exam-service migration reference content-service topics without a shared database.

IMPORTANT: Flyway checksums applied migrations. Never regenerate over one that has already run.
To add more questions later, put them in a NEW json (same category/subject/topic names) and run
with --questions-only and a new version number; the topics already exist, so only questions are emitted.
Use --skip-category instead when the category exists but the JSON introduces new subjects/topics (and exams).

JSON shape: see infra/seed-data/ugc_net.json. A question is
  {"d": "EASY|MEDIUM|HARD", "q": "text", "options": [...], "answer": 1  (or "answers": [0, 2]),
   "why": "explanation", "tags": ["UGC NET Dec 2023"], "code": "optional snippet"}
"""
import argparse, json, sys, uuid

NS = uuid.UUID('7d3c5a1e-0b7a-4c55-9a52-5a6f3c0e1d11')
SYSTEM_USER = '00000000-0000-0000-0000-000000000001'
DIFFICULTIES = {'EASY', 'MEDIUM', 'HARD'}


def uid(*parts):
    return str(uuid.uuid5(NS, '|'.join(parts)))


def q(s):
    return "'" + s.replace("'", "''") + "'"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('json_file')
    ap.add_argument('--content-out')
    ap.add_argument('--exam-out')
    ap.add_argument('--skip-category', action='store_true',
                    help='category already exists: emit new subjects/topics/questions (and exams) but not the category row')
    ap.add_argument('--questions-only', action='store_true',
                    help='content output contains only questions (category/subject/topics already exist)')
    args = ap.parse_args()
    data = json.load(open(args.json_file, encoding='utf-8'))
    cat = data['category']
    cat_id = uid('category', cat['code'])

    topic_ids, out, problems = {}, [], []
    src = f"-- Generated by infra/tools/gen_seed_sql.py from {args.json_file.split('/')[-1]}.\n" \
          "-- Edit the JSON and regenerate; never edit a migration that has already been applied.\n\n"

    if not args.questions_only and not args.skip_category:
        out.append(f"INSERT INTO categories (id, code, name, description) VALUES\n    "
                   f"({q(cat_id)}, {q(cat['code'])}, {q(cat['name'])}, {q(cat.get('description', ''))});\n")

    for si, subj in enumerate(data['subjects'], 1):
        subj_id = uid('subject', cat['code'], subj['name'])
        if not args.questions_only:
            out.append(f"INSERT INTO subjects (id, category_id, name, description, sort_order) VALUES\n    "
                       f"({q(subj_id)}, {q(cat_id)}, {q(subj['name'])}, {q(subj.get('description', ''))}, {si});\n")
        for ti, topic in enumerate(subj['topics'], 1):
            if topic['name'] in topic_ids:
                problems.append(f"duplicate topic name: {topic['name']}")
            tid = topic_ids[topic['name']] = uid('topic', cat['code'], subj['name'], topic['name'])
            if not args.questions_only:
                out.append(f"INSERT INTO topics (id, subject_id, name, description, sort_order) VALUES\n    "
                           f"({q(tid)}, {q(subj_id)}, {q(topic['name'])}, {q(topic.get('description', ''))}, {ti});\n")
            out.append(f"-- ===== {subj['name']} / {topic['name']} ({len(topic['questions'])} questions) =====\n")
            for n, qu in enumerate(topic['questions'], 1):
                where = f"{topic['name']} #{n}"
                answers = qu.get('answers', [qu['answer']] if 'answer' in qu else [])
                if qu['d'] not in DIFFICULTIES: problems.append(f"{where}: bad difficulty")
                if len(qu['options']) < 2: problems.append(f"{where}: needs 2+ options")
                if not answers or any(not 0 <= a < len(qu['options']) for a in answers):
                    problems.append(f"{where}: answer index out of range")
                if len(set(o.strip().lower() for o in qu['options'])) != len(qu['options']):
                    problems.append(f"{where}: duplicate options")
                if not qu.get('why'): problems.append(f"{where}: missing explanation")
                qtype = 'MULTIPLE_CORRECT' if len(answers) > 1 else 'SINGLE_CORRECT'
                qid = uid('question', cat['code'], subj['name'], topic['name'], qu['q'])
                vid = uid('version', cat['code'], subj['name'], topic['name'], qu['q'])
                code_col, code_val = (', code_snippet', f", {q(qu['code'])}") if qu.get('code') else ('', '')
                out.append(f"INSERT INTO questions (id, topic_id, type, difficulty, status, created_by) VALUES\n"
                           f"    ({q(qid)}, {q(tid)}, '{qtype}', '{qu['d']}', 'PUBLISHED', '{SYSTEM_USER}');")
                out.append(f"INSERT INTO question_versions (id, question_id, version_number, question_text, explanation{code_col}, created_by) VALUES\n"
                           f"    ({q(vid)}, {q(qid)}, 1,\n     {q(qu['q'])},\n     {q(qu['why'])}{code_val},\n     '{SYSTEM_USER}');")
                out.append(f"UPDATE questions SET current_version_id = {q(vid)} WHERE id = {q(qid)};")
                rows = ',\n'.join(f"    ({q(vid)}, {q(o)}, {'true' if i in answers else 'false'}, {i})"
                                  for i, o in enumerate(qu['options']))
                out.append(f"INSERT INTO question_options (question_version_id, option_text, is_correct, sort_order) VALUES\n{rows};")
                for tag in qu.get('tags', []):
                    out.append(f"INSERT INTO tags (name) VALUES ({q(tag)}) ON CONFLICT (name) DO NOTHING;")
                    out.append(f"INSERT INTO question_tags (question_id, tag_id) SELECT {q(qid)}, id FROM tags WHERE name = {q(tag)};")
                out.append('')

    exam_out = []
    for ei, ex in enumerate(data.get('exams', []), 1):
        eid = uid('exam', cat['code'], ex['title'])
        exam_out.append(f"INSERT INTO exams (id, title, category_code, duration_minutes, negative_marking, navigation_mode, status, created_by) VALUES\n"
                        f"    ({q(eid)}, {q(ex['title'])}, {q(cat['code'])}, {ex['duration_minutes']}, {ex.get('negative_marking', 0)}, "
                        f"{q(ex.get('navigation_mode', 'FREE'))}, 'PUBLISHED', '{SYSTEM_USER}');")
        srows, trows = [], []
        for si, sec in enumerate(ex['sections']):
            sid = uid('section', cat['code'], ex['title'], sec['name'])
            srows.append(f"    ({q(sid)}, {q(eid)}, {q(sec['name'])}, {si}, {sec['count']})")
            for tn in sec['topics']:
                if tn not in topic_ids: problems.append(f"exam '{ex['title']}': unknown topic '{tn}'")
                else: trows.append(f"    ({q(sid)}, {q(topic_ids[tn])})")
        exam_out.append("INSERT INTO exam_sections (id, exam_id, name, sort_order, question_count) VALUES\n" + ',\n'.join(srows) + ';')
        exam_out.append("INSERT INTO exam_section_topics (section_id, topic_id) VALUES\n" + ',\n'.join(trows) + ';\n')

    if problems:
        print('PROBLEMS:\n  - ' + '\n  - '.join(problems)); sys.exit(1)
    if args.content_out:
        open(args.content_out, 'w', encoding='utf-8').write(src + '\n'.join(out) + '\n'); print('wrote', args.content_out)
    if args.exam_out and exam_out:
        hdr = src + "-- Topic ids are the uuid5 ids generated with the content-service migration (same JSON, same names).\n\n"
        open(args.exam_out, 'w', encoding='utf-8').write(hdr + '\n'.join(exam_out)); print('wrote', args.exam_out)


if __name__ == '__main__':
    main()
